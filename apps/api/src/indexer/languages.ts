export function isConfigFile(filePath: string): boolean {
  const base = path.basename(filePath).toLowerCase();
  if (CONFIG_FILES.has(base)) return true;
  if (base.endsWith('.csproj') || base.endsWith('.sln')) return true;
  return /(^|\/)(config|configs|conf)(\/|$)/i.test(filePath) && detectLanguage(filePath) !== 'unknown';
}

const GENERATED_MARKERS = [
  '@generated',
  'AUTO-GENERATED',
  'Code generated by',
  'DO NOT EDIT',
  'This file was automatically generated',
];

export function looksGenerated(content: string): boolean {
  const head = content.slice(0, 800);
  return GENERATED_MARKERS.some((marker) => head.includes(marker));
}

export interface RoleHint {
  role: string;
  reason: string;
}

/**
 * Assigns an architectural role from path + content conventions. Used to build
 * the project map and to rank retrieval results.
 */
export function detectRole(filePath: string, content: string): RoleHint {
  const p = filePath.toLowerCase();
  const base = path.basename(p);

  if (isTestFile(filePath)) return { role: 'test', reason: 'test path or filename convention' };
  if (/(^|\/)(migrations?|migrate)(\/|$)/.test(p)) return { role: 'migration', reason: 'migrations directory' };
  // "api" as a workspace name (apps/api, packages/api, services/api) says
  // nothing about the file's role - matching it labelled every backend file in
  // a monorepo "route" and collapsed the whole architecture view into one layer.
  const apiIsWorkspaceName = /(^|\/)(apps|packages|services|libs|modules|cmd)\/api(\/|$)/.test(p);
  if (
    /(^|\/)(routes?|router|routers|endpoints|controllers?|handlers?)(\/|$)/.test(p) ||
    (!apiIsWorkspaceName && /(^|\/)api(\/|$)/.test(p))
  ) {
    return { role: p.includes('controller') ? 'controller' : 'route', reason: 'routing/controller directory' };
  }
  if (/(^|\/)(middlewares?|interceptors?|guards?|filters?)(\/|$)/.test(p)) {
    return { role: 'middleware', reason: 'middleware directory' };
  }
  if (/(^|\/)(services?|usecases?|domain|business)(\/|$)/.test(p) || /service\.[a-z]+$/.test(base)) {
    return { role: 'service', reason: 'service layer convention' };
  }
  if (/(^|\/)(repositor(y|ies)|daos?|stores?|persistence)(\/|$)/.test(p) || /repository\.[a-z]+$/.test(base)) {
    return { role: 'repository', reason: 'data-access layer convention' };
  }
  if (/(^|\/)(models?|entities|schemas?|dtos?)(\/|$)/.test(p)) return { role: 'model', reason: 'model directory' };
  if (/(^|\/)(components?|views?|pages?|screens?|widgets?)(\/|$)/.test(p)) {
    return { role: 'component', reason: 'UI directory' };
  }
  if (/(^|\/)(hooks?|composables?)(\/|$)/.test(p)) return { role: 'hook', reason: 'hooks directory' };
  if (/(^|\/)(utils?|helpers?|lib|libs|common|shared)(\/|$)/.test(p)) {
    return { role: 'util', reason: 'utility directory' };
  }
  if (/(^|\/)(config|configs|settings)(\/|$)/.test(p) || isConfigFile(filePath)) {
    return { role: 'config', reason: 'configuration file' };
  }
  if (/(^|\/)(jobs?|workers?|tasks?|queues?|cron)(\/|$)/.test(p)) return { role: 'worker', reason: 'background job directory' };
  if (/(^|\/)(auth|authentication|authorization|security)(\/|$)/.test(p)) {
    return { role: 'auth', reason: 'authentication directory' };
  }

  if (/@(Controller|RestController)\b/.test(content)) return { role: 'controller', reason: 'framework controller annotation' };
  if (/@(Injectable|Service)\b/.test(content)) return { role: 'service', reason: 'framework service annotation' };
  if (/\b(app|router)\.(get|post|put|patch|delete)\s*\(/.test(content)) {
    return { role: 'route', reason: 'HTTP route registrations found in file' };
  }
  if (/\bexport\s+default\s+function\s+[A-Z]/.test(content) || /return\s*\(?\s*</.test(content)) {
    return { role: 'component', reason: 'renders JSX' };
  }

  // A conventional filename alone is not enough: most `index.ts` files are
  // re-export barrels, and labelling them entry points made whole directories
  // look like process entry points in the architecture view.
  const entry = ['main', 'index', 'app', 'server', 'program'].includes(base.split('.')[0] ?? '');
  if (entry) {
    const starts =
      /\.(listen|start|run)\s*\(|createServer\s*\(|createRoot\s*\(|ReactDOM\.render\s*\(|app\.mount\s*\(|if\s+__name__\s*==|func\s+main\s*\(|static\s+void\s+[Mm]ain\s*\(/.test(
        content,
      );
    if (starts) return { role: 'entrypoint', reason: 'conventional entry-point filename that starts the process' };
    if (/^\s*(import|export)\b/m.test(content) && !/\bfunction\b|\bclass\b/.test(content)) {
      return { role: 'barrel', reason: 're-export barrel' };
    }
  }

  return { role: 'unknown', reason: 'no convention matched' };
}
