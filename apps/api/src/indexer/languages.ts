const TEST_PATH = /(^|\/)(tests?|__tests__|spec|e2e|cypress)(\/|$)/i;
const TEST_FILE = /\.(test|spec)\.[a-z]+$|_test\.[a-z]+$|^test_[^/]+\.py$|Test\.java$|Tests\.cs$/;

export function isTestFile(filePath: string): boolean {
  const base = path.basename(filePath);
  return TEST_PATH.test(filePath) || TEST_FILE.test(base);
}

